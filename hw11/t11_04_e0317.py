# множення чисел за алгоритмом Карацуби
# реалізація працює з рядками, щоб коректно обробляти дуже великі числа

import sys
sys.set_int_max_str_digits(10**6)


def karatsuba(x, y):
    """
    функція множення Карацуби для двох чисел у вигляді рядків
    """
    # базовий випадок: якщо числа короткі, просто перетворюємо їх у числа і перемножуємо
    if len(x) == 1 or len(y) == 1:
        return str(int(x) * int(y))
    
    # визначаємо максимальну довжину числа і половину для розбиття
    n = max(len(x), len(y))
    half = n // 2
    
    # додаємо нулі попереду для рівної довжини обох чисел
    x = '0' * (n - len(x)) + x
    y = '0' * (n - len(y)) + y
    
    # розділяємо числа на дві частини: ліва і права половини
    x_high, x_low = x[:-half], x[-half:]
    y_high, y_low = y[:-half], y[-half:]
    
    # рекурсивні виклики для трьох необхідних множень
    z0 = karatsuba(x_low, y_low)  # (b * d)
    z1 = karatsuba(str(int(x_low) + int(x_high)), str(int(y_low) + int(y_high)))  # ((a+b) * (c+d))
    z2 = karatsuba(x_high, y_high)  # (a * c)
    
    # Карацуба: комбінуємо результати множень
    result = int(z2) * (10 ** (2 * half)) + (int(z1) - int(z2) - int(z0)) * (10 ** half) + int(z0)
    
    return str(result)

a, b = input().strip().split()

result = karatsuba(a, b)

print(result)