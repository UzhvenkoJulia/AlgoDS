# Сортування бульбашкою
# Сортування – алгоритми зі складністю n²

def bubble_sort_count_swaps(arr):
    # масив arr як вхідний параметр
    n = len(arr)  # отримуємо к-сть елементів у масиві
    swap_count = 0  # лічильник кількості обмінів
    
    # проходимо по всьому масиву n-1 разів
    for i in range(n - 1):
        swapped = False  # змінна для перевірки, чи були обміни
        
        # проходимо по масиву, порівнюючи сусідні елементи
        for j in range(n - 1 - i):  # останні i елементів уже відсортовані
            if arr[j] > arr[j + 1]:  # якщо елемент більший за наступний
                arr[j], arr[j + 1] = arr[j + 1], arr[j]  
                swap_count += 1 
                swapped = True  # позначаємо, що відбувся обмін
        
        # якщо не було жодного обміну, завершимо сортування достроково
        if not swapped:
            break
    
    return swap_count  

n = int(input())  # к-сть елементів у масиві
arr = list(map(int, input().split()))  # масив чисел

# виконуємо сортування та виводимо к-сть обмінів
print(bubble_sort_count_swaps(arr))